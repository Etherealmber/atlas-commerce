import { beforeEach, expect, it, vi } from 'vitest';
const mocks = vi.hoisted(() => ({ token: 'first' as string | null, get: vi.fn() }));
vi.mock('../auth', () => ({ getToken: () => mocks.token }));
vi.mock('../api', () => ({ api: { getMetricsDaily: mocks.get } }));
import { __resetMetricSeries, loadMetricSeries, subscribeMetricSeries } from '../lib/metricSeries';
const payload = (value: number) => ({ data: { days: 1, dates: ['2026-10-20'], series: { money_in: [value] }, kinds: {} } });
beforeEach(() => { mocks.token = 'first'; mocks.get.mockReset(); __resetMetricSeries(); });
it('keeps stale data visible during refresh but never across sessions', async () => {
  mocks.get.mockResolvedValueOnce(payload(100));
  const seen: any[] = [];
  const off = subscribeMetricSeries((s) => seen.push(s));
  await loadMetricSeries();
  let resolve!: (value: unknown) => void;
  mocks.get.mockImplementationOnce(() => new Promise((r) => { resolve = r; }));
  const pending = loadMetricSeries(true);
  await Promise.resolve();
  expect(seen.at(-1).data.series.money_in).toEqual([100]);
  expect(seen.at(-1).loading).toBe(true);
  mocks.token = 'second';
  mocks.get.mockResolvedValueOnce(payload(200));
  await loadMetricSeries();
  resolve(payload(999));
  await pending;
  expect(seen.at(-1).data.series.money_in).toEqual([200]);
  mocks.token = null;
  await loadMetricSeries();
  expect(seen.at(-1).data).toBeNull();
  off();
});

 it('notifies existing subscribers immediately when a new subscriber observes logout', async () => {
  mocks.get.mockResolvedValueOnce(payload(100));
  const first: any[] = [];
  const offFirst = subscribeMetricSeries((s) => first.push(s));
  await loadMetricSeries();
  expect(first.at(-1).data.series.money_in).toEqual([100]);
  mocks.token = null;
  const second: any[] = [];
  const offSecond = subscribeMetricSeries((s) => second.push(s));
  expect(first.at(-1).data).toBeNull();
  expect(second.at(-1).data).toBeNull();
  offFirst(); offSecond();
});
