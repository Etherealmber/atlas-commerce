#!/usr/bin/env node
/**
 * Bundles migrations/*.sql into worker/lib/demo/migrations.generated.ts so the
 * demo sandbox can replay them under ANY bundler. `import.meta.glob` is
 * Vite-only: under plain `wrangler dev` / esbuild it is undefined and crashed
 * the Worker at boot. `worker/__tests__/demo-migrations-sync.test.ts` fails
 * when this file is stale — run `npm run gen:demo-migrations`.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export function renderDemoMigrations() {
  const dir = join(root, 'migrations');
  const names = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
  const items = names.map((name) => `  { name: ${JSON.stringify(name)}, sql: ${JSON.stringify(readFileSync(join(dir, name), 'utf8'))} },`);
  return [
    '// AUTO-GENERATED by scripts/gen-demo-migrations.mjs — do not edit by hand.',
    '// Source: migrations/*.sql (replayed into each demo sandbox).',
    'export const DEMO_MIGRATIONS_GENERATED: { name: string; sql: string }[] = [',
    ...items,
    '];',
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(root, 'worker/lib/demo/migrations.generated.ts');
  writeFileSync(out, renderDemoMigrations());
  console.log(`wrote ${out}`);
}
