/**
 * REVIEW-ONLY Android possession primitive. NOT imported by any production route.
 * Even a valid proof MUST NOT suppress OTP in this release. No flag enables it.
 * All records/context below must be loaded/derived by the server, never spread
 * from an HTTP request. Only signature is client supplied.
 */
export const ANDROID_DEVICE_PROOF_POLICY = 'review-only-otp-required' as const;
export const DEVICE_CREDENTIAL_TTL_MS = 30 * 24 * 60 * 60 * 1000;
export const DEVICE_CHALLENGE_TTL_MS = 120_000;

export interface DeviceProofScope {
  /** Immutable deployment/tenant ID, not company name or client input. */
  tenantId: string;
  /** Canonical HTTPS origin, including a non-default port. */
  origin: string;
  /** Immutable user ID (including a reserved owner ID), not a reusable username. */
  subjectId: string;
  /** Server-side security epoch; changes on password/role/security reset. */
  accountEpoch: string;
}
export interface DeviceCredential extends DeviceProofScope {
  id: string;
  publicKey: JsonWebKey;
  enrolledVia: 'email-otp';
  enrolledAt: number;
  expiresAt: number;
  revokedAt: number | null;
}
export interface DeviceChallenge extends DeviceProofScope {
  id: string;
  credentialId: string;
  purpose: 'return-login';
  /** 32 random bytes, canonical unpadded base64url. Generated by server. */
  nonce: string;
  issuedAt: number;
  expiresAt: number;
  consumedAt: number | null;
}
export interface DeviceProofContext extends DeviceProofScope {
  now: number;
  /** Results of existing server gates, NEVER request booleans. */
  passwordVerified: boolean;
  accountActive: boolean;
  abuseAllowed: boolean;
  requireOtpForRisk: boolean;
  /** Telemetry/risk input, deliberately NOT a substitute for possession. */
  ipChanged: boolean;
}
export type DeviceProofReason = 'REVIEW_REQUIRED' | 'BAD_PASSWORD' | 'OTP_REQUIRED'
  | 'RISK_REQUIRES_OTP' | 'INVALID_PROOF' | 'UNAVAILABLE';
export interface DeviceProofResult {
  /** Always true until reviewed integration is implemented separately. */
  otpRequired: true;
  candidateProofVerified: boolean;
  reason: DeviceProofReason;
}

const encoder = new TextEncoder();
const scopeFields = ['tenantId', 'origin', 'subjectId', 'accountEpoch'] as const;
const identifier = (s: unknown): s is string => typeof s === 'string' && /^[A-Za-z0-9._:-]{1,128}$/.test(s);
function validScope(scope: DeviceProofScope): boolean {
  if (![scope.tenantId, scope.subjectId, scope.accountEpoch].every(identifier)) return false;
  try {
    const u = new URL(scope.origin);
    return u.protocol === 'https:' && !u.username && !u.password && u.origin === scope.origin;
  } catch { return false; }
}
function matches(a: DeviceProofScope, b: DeviceProofScope): boolean {
  return scopeFields.every((key) => a[key] === b[key]);
}
function decodeBase64url(value: string, size: number): Uint8Array<ArrayBuffer> | null {
  if (typeof value !== 'string' || !/^[A-Za-z0-9_-]+$/.test(value) || value.length !== Math.ceil(size * 4 / 3)) return null;
  try {
    const raw = atob(value.replace(/-/g, '+').replace(/_/g, '/') + '='.repeat((4 - value.length % 4) % 4));
    const canonical = btoa(raw).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
    if (raw.length !== size || canonical !== value) return null;
    return Uint8Array.from(raw, (char) => char.charCodeAt(0));
  } catch { return null; }
}

/** Stable UTF-8 signing bytes; arrays avoid ambiguous delimiters/key ordering.
 * Android SHA256withECDSA produces DER: the future native adapter must strictly
 * convert DER r/s to the 64-byte IEEE-P1363 form used by Web Crypto here.
 * Do not sign a client-created challenge or reconstruct fields from client JSON.
 */
export function deviceChallengeBytes(challenge: DeviceChallenge): Uint8Array<ArrayBuffer> {
  return encoder.encode(JSON.stringify([
    'atlas.android.device-proof', 1, 'ES256', challenge.purpose,
    challenge.tenantId, challenge.origin, challenge.subjectId, challenge.accountEpoch,
    challenge.credentialId, challenge.id, challenge.nonce, challenge.issuedAt, challenge.expiresAt,
  ]));
}

export interface DeviceProofCommit {
  credential: DeviceCredential;
  challenge: DeviceChallenge;
  checkedAt: number;
}
/** Future persistence adapter MUST atomically consume the challenge only if all
 * scope/epoch/key/expiry/revocation predicates are still current. False on a lost
 * race, account mutation or revocation. This module supplies NO production adapter.
 */
export type CommitDeviceProof = (expected: DeviceProofCommit) => Promise<boolean>;

function result(reason: DeviceProofReason, candidateProofVerified = false): DeviceProofResult {
  return { otpRequired: true, candidateProofVerified, reason };
}

/** No tokens, no logging, no enrollment, no new endpoint and no OTP bypass. */
export async function evaluateAndroidDeviceProof(
  context: DeviceProofContext,
  credential: DeviceCredential | null,
  challenge: DeviceChallenge | null,
  signature: string | null,
  commitIfCurrent: CommitDeviceProof,
): Promise<DeviceProofResult> {
  try {
    if (!context.passwordVerified) return result('BAD_PASSWORD');
    if (!context.accountActive || !context.abuseAllowed || context.requireOtpForRisk) return result('RISK_REQUIRES_OTP');
    if (!credential || !challenge || !signature) return result('OTP_REQUIRED');
    if (!validScope(context) || !matches(context, credential) || !matches(context, challenge)) return result('INVALID_PROOF');
    if (![context.now, credential.enrolledAt, credential.expiresAt, challenge.issuedAt, challenge.expiresAt].every(Number.isSafeInteger)) return result('INVALID_PROOF');
    if (!identifier(credential.id) || !identifier(challenge.id) || challenge.credentialId !== credential.id
      || challenge.purpose !== 'return-login' || !decodeBase64url(challenge.nonce, 32)) return result('INVALID_PROOF');
    if (credential.enrolledVia !== 'email-otp' || credential.revokedAt !== null || challenge.consumedAt !== null
      || credential.enrolledAt > context.now || credential.expiresAt <= context.now
      || credential.expiresAt <= credential.enrolledAt || credential.expiresAt - credential.enrolledAt > DEVICE_CREDENTIAL_TTL_MS
      || challenge.issuedAt < credential.enrolledAt || challenge.issuedAt > context.now
      || challenge.expiresAt <= context.now || challenge.expiresAt > credential.expiresAt
      || challenge.expiresAt <= challenge.issuedAt || challenge.expiresAt - challenge.issuedAt > DEVICE_CHALLENGE_TTL_MS) return result('INVALID_PROOF');

    const jwk = credential.publicKey;
    // Accept ONLY a public P-256 key. Never import private/symmetric key material.
    if (!jwk || jwk.kty !== 'EC' || jwk.crv !== 'P-256' || jwk.d !== undefined
      || (jwk.alg !== undefined && jwk.alg !== 'ES256')
      || !decodeBase64url(jwk.x!, 32) || !decodeBase64url(jwk.y!, 32)) return result('INVALID_PROOF');
    const sig = decodeBase64url(signature, 64);
    if (!sig) return result('INVALID_PROOF');
    const publicKey = await crypto.subtle.importKey('jwk', {
      kty: 'EC', crv: 'P-256', x: jwk.x, y: jwk.y, ext: true,
    }, { name: 'ECDSA', namedCurve: 'P-256' }, false, ['verify']);
    const verified = await crypto.subtle.verify({ name: 'ECDSA', hash: 'SHA-256' }, publicKey, sig, deviceChallengeBytes(challenge));
    if (!verified) return result('INVALID_PROOF');
    if (!(await commitIfCurrent({ credential, challenge, checkedAt: context.now }))) return result('INVALID_PROOF');
    return result('REVIEW_REQUIRED', true);
  } catch {
    // Do not surface raw crypto/storage exception text or caller input.
    return result('UNAVAILABLE');
  }
}
